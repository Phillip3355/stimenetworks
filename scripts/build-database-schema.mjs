import { readFile, writeFile, readdir } from 'node:fs/promises';
const database = new URL('../database/', import.meta.url);
let sql = '-- Generated by scripts/build-database-schema.mjs. Fresh installations only.\nBEGIN;\n';
sql += await readFile(new URL('foundation.sql', database), 'utf8');
for (const name of (await readdir(new URL('migrations/', database))).filter(name => name.endsWith('.sql')).sort()) {
  sql += '\n' + (await readFile(new URL(`migrations/${name}`, database), 'utf8')).replace(/^BEGIN;|^COMMIT;/gm, '');
}
sql += '\n' + await readFile(new URL('realtime.sql', database), 'utf8');
sql += '\nCOMMIT;\n';
await writeFile(new URL('schema.sql', database), sql);
